	public static void changeLuminosity(GrayU8 input, int delta){
		for (int y = 0; y < input.height; ++y) {
			for (int x = 0; x < input.width; ++x) {
				int gl = input.get(x, y);
				gl = gl+delta;
				if(gl>255){
					gl=255;
				}
				else if(gl<0){
					gl=0;
				}
				input.set(x, y, gl);
			}
		}
	}

