	public static void egalisation(GrayU8 input){
		int[] hist = new int[256];
		for(int i=0;i<256;i++){
			hist[i]=0;
		}
		for (int y = 0; y < input.height; ++y) {
			for (int x = 0; x < input.width; ++x) {
				int gl = input.get(x, y);
				hist[gl]+=1;	
			}
		}
		int[] histCumul= new int[256];
		histCumul[0]=hist[0];
		for(int i=1;i<256;i++){
			histCumul[i]+=histCumul[i-1]+hist[i];
		}
		for (int y = 0; y < input.height; ++y) {
			for (int x = 0; x < input.width; ++x) {
				int gl = input.get(x, y);
				gl = (histCumul[gl]*255)/(input.height*input.width);
				input.set(x, y, gl);
			}
		}
	}
    

