	public static void extensionLinéaireUnoptimized(GrayU8 input){
		int max =0;
		int min = 255;
		for (int y = 0; y < input.height; ++y) {
			for (int x = 0; x < input.width; ++x) {
				int gl = input.get(x, y);
				if (gl < min){
					min=gl;
				}
				if(gl > max){
					max=gl;
				}
			}
		}
		for (int y = 0; y < input.height; ++y) {
			for (int x = 0; x < input.width; ++x) {
				int gl = input.get(x, y);
				gl = (255*(gl-min))/(max-min);
				input.set(x, y, gl);
			}
		}
	}

	//////////////////////						Partie 2					  //////////////////////

	public static void extensionLinéaireLUT(GrayU8 input){
		int max =0;
		int min = 255;
		for (int y = 0; y < input.height; ++y) {
			for (int x = 0; x < input.width; ++x) {
				int gl = input.get(x, y);
				if (gl < min){
					min=gl;
				}
				if(gl > max){
					max=gl;
				}
			}
		}
		int[] LUT = new int[256];
		for(int i =0;i<256;i++){
			LUT[i]=(255*(i-min))/(max-min);
		}
		for (int y = 0; y < input.height; ++y) {
			for (int x = 0; x < input.width; ++x) {
				int gl = input.get(x, y);
				gl = LUT[gl];
				input.set(x, y, gl);	
			}
		}
	}

